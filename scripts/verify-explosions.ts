import assert from 'node:assert/strict';
import { NullEngine } from '@babylonjs/core/Engines/nullEngine';
import { Scene } from '@babylonjs/core/scene';
import { FreeCamera } from '@babylonjs/core/Cameras/freeCamera';
import { Vector3 } from '@babylonjs/core/Maths/math.vector';
import { createExplosions } from '../src/client/game/explosions';

const engine = new NullEngine({ renderWidth: 960, renderHeight: 540, textureSize: 512, deterministicLockstep: false, lockstepMaxSteps: 4 });
const scene = new Scene(engine);
const camera = new FreeCamera('explosion-proof-camera', new Vector3(0, 8, -12), scene);
camera.setTarget(Vector3.Zero());
const explosions = createExplosions(scene);
try {
  const allocatedMeshes = scene.meshes.length;
  const allocatedMaterials = scene.materials.length;
  const triangles = scene.meshes.reduce((total, mesh) => total + mesh.getTotalIndices() / 3, 0);
  assert.equal(explosions.stats.capacity, 2);
  assert.equal(allocatedMeshes, 46);
  assert.ok(triangles < 5_000, `Both complete pooled effects stay below 5,000 triangles, observed ${triangles}.`);
  assert.equal(explosions.stats.active, 0);
  assert.ok(explosions.roots.every((root) => !root.isEnabled()));
  await explosions.ready();
  explosions.trigger({ x: 2, y: 0.6, z: -1 }, 75);
  assert.equal(explosions.stats.active, 1);
  const root = explosions.roots[0]; assert.ok(root);
  assert.deepEqual(root.position.asArray(), [2, 0.6, -1]);
  const core = scene.getMeshByName('explosion-core-0');
  const fire = scene.getMeshByName('explosion-fire-0-0');
  const smoke = scene.getMeshByName('explosion-smoke-0-0');
  const spark = scene.getMeshByName('explosion-spark-0-0');
  assert.ok(core && fire && smoke && spark);
  assert.ok(core.isVisible && core.visibility > 0, 'Trigger immediately exposes the flash.');
  const initialSpark = spark.position.clone();
  explosions.pulse(0.20);
  assert.ok(spark.position.subtract(initialSpark).length() > 0.5, 'Sparks follow separate moving trajectories.');
  assert.ok(core.scaling.x > 2, 'The flash expands before fading.');
  explosions.pulse(0.35);
  assert.equal(core.isVisible, false, 'The main flash lasts less than 0.4 seconds.');
  assert.equal(fire.isVisible, false);
  assert.ok(smoke.isVisible && smoke.visibility > 0);
  const smokeHeight = smoke.position.y;
  explosions.pulse(0.4);
  assert.ok(smoke.position.y > smokeHeight, 'Smoke continues rising after the flash ends.');
  explosions.trigger({ x: -2, y: 3.5, z: 2 }, 44);
  assert.equal(explosions.stats.active, 2);
  const airborneScorch = scene.getMeshByName('explosion-scorch-1'); assert.ok(airborneScorch);
  assert.equal(airborneScorch.isVisible, false, 'An airborne blast does not paint a disconnected scorch onto the floor.');
  explosions.trigger({ x: 4, y: 1, z: 1 }, 3);
  assert.equal(explosions.stats.active, 2, 'A third trigger reuses the oldest slot.');
  assert.equal(scene.meshes.length, allocatedMeshes);
  assert.equal(scene.materials.length, allocatedMaterials);
  scene.render();
  explosions.pulse(3);
  assert.equal(explosions.stats.active, 0);
  assert.ok(explosions.roots.every((candidate) => !candidate.isEnabled()));
  explosions.trigger({ x: 0, y: 0.5, z: 0 });
  explosions.clear();
  assert.equal(explosions.stats.active, 0);
  assert.ok(explosions.roots.every((candidate) => !candidate.isEnabled()), 'Rematch clears every finishing particle.');
  explosions.trigger({ x: 0, y: 0.5, z: 0 });
  assert.equal(explosions.roots[0], root, 'Cleared effects reuse the same root and geometry.');
  process.stdout.write(`${JSON.stringify({ check: 'PASS: pooled defeat explosion, flash, sparks, smoke, expiry and reuse', ...explosions.stats, triangles })}\n`);
} finally {
  explosions.dispose(); explosions.dispose();
  assert.equal(scene.meshes.length, 0);
  assert.equal(scene.materials.length, 0);
  scene.dispose(); engine.dispose();
}
